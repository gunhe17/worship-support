import subprocess, glob, os
import numpy as np
import essentia.standard as es

def detect_keys_from_youtube(url, win_sec=15, hop_sec=5,
                             switch_penalty=6.0, prior_weight=2.0):
    # ---- 다운로드 ----
    for f in glob.glob("audio.*"):
        os.remove(f)
    r = subprocess.run([
        "yt-dlp", "-x", "--audio-format", "wav", "--audio-quality", "0",
        "-o", "audio.%(ext)s", url
    ], capture_output=True, text=True)
    if r.returncode != 0:
        print("다운로드 실패:\n", r.stderr[-500:]); return

    path = glob.glob("audio.*")[0]
    audio = es.MonoLoader(filename=path)()
    sr = 44100
    win, hop = int(sr*win_sec), int(sr*hop_sec)

    # ---- 1) 구간별 키 추출 ----
    raw = []
    for start in range(0, max(1, len(audio)-win+1), hop):
        seg = audio[start:start+win].copy()
        k, s, st = es.KeyExtractor()(seg)
        raw.append((start/sr, f"{k} {s}", st))

    # ---- 2) 비터비 평활화 + 전역 사전확률 ----
    states = sorted({k for _, k, _ in raw})
    S = len(states); idx = {k: i for i, k in enumerate(states)}

    support = np.zeros(S)
    for _, k, st in raw: support[idx[k]] += st
    prior = np.log(support/support.sum() + 1e-6) * prior_weight

    def emit(rep, st):
        p = np.full(S, (1.0-st)/(S-1)); p[idx[rep]] = st
        return np.log(p + 1e-9) + prior

    T = len(raw)
    dp = np.full((T, S), -1e18); bp = np.zeros((T, S), dtype=int)
    dp[0] = emit(raw[0][1], raw[0][2])
    for t in range(1, T):
        e = emit(raw[t][1], raw[t][2])
        for s in range(S):
            tr = dp[t-1] - switch_penalty; tr[s] = dp[t-1][s]
            b = int(np.argmax(tr)); dp[t][s] = tr[b] + e[s]; bp[t][s] = b
    path = [int(np.argmax(dp[-1]))]
    for t in range(T-1, 0, -1): path.append(bp[t][path[-1]])
    smooth = [states[i] for i in path[::-1]]

    # ---- 3) 구간 압축 ----
    segs = []
    for t, (sec, _, _) in enumerate(raw):
        if not segs or segs[-1][1] != smooth[t]:
            segs.append((sec, smooth[t]))

    # ---- 출력 ----
    print("=" * 40)
    for sec, k in segs:
        print(f"  {sec:6.1f}s 부터 : {k}")
    changes = segs[1:]
    print("=" * 40)
    if changes:
        print(f"키 변화 {len(changes)}회:")
        for sec, k in changes:
            print(f"  - {sec:.0f}초 부근 → {k}")
    else:
        print(f"단일 키 곡: {segs[0][1]}")
    print("=" * 40)
    return segs, raw

