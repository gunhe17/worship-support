def detect_key_librosa(y, sr):
    """Essentia KeyExtractor 대체: 크로마(chroma) + Krumhansl 상관 매칭"""
    chroma = librosa.feature.chroma_cqt(y=y, sr=sr).mean(axis=1)
    if chroma.sum() > 0:
        chroma = chroma / chroma.sum()
    best_k, best_s, best_c = "C", "major", -2.0
    for i in range(12):
        for prof, name in [(MAJOR,'major'), (MINOR,'minor')]:
            c = np.corrcoef(chroma, np.roll(prof, i))[0,1]
            if c > best_c:
                best_c, best_k, best_s = c, PITCH[i], name
    strength = max(0.0, min(1.0, best_c))   # 신뢰도 0~1 클램프
    return best_k, best_s, strength


